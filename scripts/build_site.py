#!/usr/bin/env python3
"""Regenerate the data files of the static site in site/ from the workbook and the docs.

    python3 scripts/build_site.py

Writes:
    site/data/model-data.js      inputs, stablecoin supply, parameters and scenario row (the pages compute the model themselves)
    site/data/model-inputs.csv   the same inputs as a plain table
    site/data/docs.js            the markdown docs, for the docs viewer
    site/downloads/              a copy of the workbook

Only input cells are read, so the workbook does not need to have been recalculated.
Plain .js files are used, not JSON fetched at run time, so the site also works when
opened straight from disk (file://) with no web server.
"""
import csv
import json
import shutil
from datetime import date

import openpyxl

import wb as lib

SITE = lib.ROOT / "site"
DOCS = [  # slug, title, path
    ("overview", "Overview", "README.md"),
    ("methodology", "Methodology", "docs/methodology.md"),
    ("workbook-guide", "Workbook guide", "docs/workbook-guide.md"),
    ("update-guide", "Update guide", "docs/update-guide.md"),
    ("toolset", "Toolset", "docs/toolset.md"),
    ("web-app", "Web app and portal", "docs/web-app.md"),
    ("data-dictionary", "Data dictionary", "docs/data-dictionary.md"),
    ("changelog", "Changelog", "CHANGELOG.md"),
]

book = openpyxl.load_workbook(lib.WORKBOOK)
rows, scenario = lib.read_inputs(book["Model"])

# "locked USD" for the liquidity-flow model: stablecoin supply, kept outside the workbook
stable_file = lib.ROOT / "data" / "stablecoins.csv"
stable = {}
if stable_file.exists():
    with open(stable_file) as f:
        stable = {r["quarter"]: float(r["stablecoins_usd_trillion"]) for r in csv.DictReader(f)}
for r in rows:
    r["stable"] = stable.get(r["quarter"])
no_stable = [r["quarter"] for r in rows if r["stable"] is None]
data = {
    "generated": date.today().isoformat(),
    "version": str(book["Guide"]["B2"].value).rsplit(" ", 1)[-1],
    "latest": rows[-1]["quarter"],
    "series": {k: {"label": d, "unit": u} for k, (_, d, u) in lib.INPUTS.items()},
    "params": lib.read_params(book),
    "quarters": rows,
    "scenario": scenario,
}

(SITE / "data").mkdir(parents=True, exist_ok=True)
(SITE / "downloads").mkdir(exist_ok=True)
(SITE / "data" / "model-data.js").write_text(
    "// Generated by scripts/build_site.py from docs/crypto_model_v2.xlsx. Do not edit by hand.\n"
    f"window.MODEL_DATA = {json.dumps(data, indent=1, ensure_ascii=False)};\n")

with open(SITE / "data" / "model-inputs.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["quarter"] + list(lib.INPUTS) + ["stablecoins", "estimated"])
    for r in rows:
        w.writerow([r["quarter"]] + [r[k] for k in lib.INPUTS] + [r["stable"], " ".join(r.get("estimated", []))])

docs = [{"slug": s, "title": t, "path": p, "md": (lib.ROOT / p).read_text()} for s, t, p in DOCS if (lib.ROOT / p).exists()]
(SITE / "data" / "docs.js").write_text(
    "// Generated by scripts/build_site.py from the markdown docs. Do not edit by hand.\n"
    f"window.DOCS = {json.dumps(docs, ensure_ascii=False)};\n")

shutil.copy2(lib.WORKBOOK, SITE / "downloads" / lib.WORKBOOK.name)

print(f"site data rebuilt: {len(rows)} quarters to {data['latest']}, {len(docs)} docs, workbook {data['version']}")
if no_stable:
    print(f"WARNING: no stablecoin supply for {', '.join(no_stable)}. Run scripts/fetch_stablecoins.py; "
          "the liquidity-flow view needs it for every quarter.")
missing = [p for _, _, p in DOCS if not (lib.ROOT / p).exists()]
if missing:
    print("skipped (not found):", ", ".join(missing))
